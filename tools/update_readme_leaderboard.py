#!/usr/bin/env python3
"""Render the README tables from a frozen leaderboard; no inference or fitting."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "published_runs/2026-10-29-leaderboard-decision-models/results.json"
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN GENERATED LEADERBOARD -->"
END = "<!-- END GENERATED LEADERBOARD -->"


def render(data):
    lines = [BEGIN, "<!-- Generated by tools/update_readme_leaderboard.py; point SOURCE at a reviewed new archive to update. -->"]
    for key, title in (("wildguard", "WildGuardTest: prompt harmfulness"),
                       ("hatexplain", "HateXplain: hate versus non-hate")):
        dataset = data["datasets"][key]
        lines.extend(["", f"### {title}", "",
                      f"{dataset['n']:,} test items: {dataset['positives']:,} violations and {dataset['negatives']:,} compliant items under the benchmark policy.", "",
                      "| Rank | Model / method | Balanced accuracy ↑ | Macro-F1 ↑ | False-block rate ↓ | Miss rate ↓ | Unresolved |",
                      "|---:|---|---:|---:|---:|---:|---:|"])
        for row in dataset["profiles"]["balanced"]["rows"]:
            m = row["metrics"]
            values = [f"{m[k] * 100:.2f}%" for k in
                      ("balanced_accuracy", "macro_f1", "false_positive_rate", "false_negative_rate")]
            label = row["label"].replace("|", "\\|")
            lines.append(f"| {row['rank']} | {label} | " + " | ".join(values) + f" | {m['unresolved']} |")
    return "\n".join(lines) + "\n\n" + END


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if README tables differ from the archived results")
    args = parser.parse_args()
    current = README.read_text(encoding="utf-8")
    if current.count(BEGIN) != 1 or current.count(END) != 1:
        parser.error("Expected exactly one pair of README leaderboard markers")
    start, finish = current.index(BEGIN), current.index(END) + len(END)
    if finish < start:
        parser.error("Leaderboard markers are out of order")
    generated = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    expected = current[:start] + generated + current[finish:]
    if args.check:
        if expected != current:
            parser.exit(1, "README leaderboard is stale; run python3 tools/update_readme_leaderboard.py\n")
        print("README leaderboard matches the frozen results.")
    else:
        README.write_text(expected, encoding="utf-8")
        print("Updated README leaderboard from " + SOURCE.relative_to(ROOT).as_posix())


if __name__ == "__main__":
    main()
